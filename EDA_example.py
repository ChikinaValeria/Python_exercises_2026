import pandas as pd

# EDA (Exploratory Data Analysis) — это «разведочный анализ данных».
# Грубо говоря, это первый этап работы с любым датасетом, когда мы просто пытаемся понять, что у нас есть
# Основные цели EDA:
# Понять структуру данных
# Сколько строк и колонок, какие типы данных (int, float, object)
# Есть ли пропущенные значения

# Найти аномалии и пропуски
# Пустые значения (NaN)
# Странные цифры или опечатки в текстовых колонках

# Посмотреть распределение данных
# Средние, медианы, минимумы, максимумы
# Частотные распределения категорий

# Найти связи между колонками
# Корреляции числовых признаков
# Таблицы сопряженности категориальных колонок

# Проверить гипотезы и подготовить данные к моделям
# Нужно ли нормализовать, удалить выбросы, объединить колонки

# создаём DataFrame
data = {
    "Name": ["Anna", "Maria", "Elena", None, "Olga"],
    "Age": [25, None, 30, 22, 28],
    "City": ["Helsinki", "Espoo", None, "Tampere", "Turku"],
    "Humidity": [50, 60, None, 55, 48]
}

df = pd.DataFrame(data)

# 1. Быстрый взгляд на данные
print("Первые строки:")
print(df.head())

# 2. Типы данных и пропуски
print("\nИнформация о DataFrame:")
print(df.info())

# 3. Статистика для числовых колонок
print("\nСтатистика по числовым колонкам:")
print(df.describe())

# 4. Сколько пропусков в каждой колонке
print("\nКоличество пустых значений:")
print(df.isna().sum())

# 5. Среднее арифметическое влажности
print("\nСредняя влажность:", df["Humidity"].mean())